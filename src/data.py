import json
from pathlib import Path

import nltk
import numpy as np
from nltk.corpus import treebank
from nltk.tree import Tree

def load_all_trees():
    nltk.download("treebank", quiet=True)
    trees = list(treebank.parsed_sents())
    assert len(trees) == 3914, f"Expected 3914 trees, found {len(trees)}"
    return trees

def get_partitions(trees):
    indices = np.arange(len(trees))
    np.random.seed(42)
    np.random.shuffle(indices)

    return {
        "A": indices[:1305].tolist(),
        "B": indices[1305:2610].tolist(),
        "C": indices[2610:3914].tolist(),
    }


def split_partition_a(partition_a):
    shuffled = np.array(partition_a, dtype=int)
    np.random.seed(42)
    np.random.shuffle(shuffled)

    n_train = int(0.80 * len(shuffled))
    n_val = int(0.10 * len(shuffled))

    return {
        "train": shuffled[:n_train].tolist(),
        "validation": shuffled[n_train:n_train + n_val].tolist(),
        "test": shuffled[n_train + n_val:].tolist(),
    }

trees = load_all_trees()
partitions = get_partitions(trees)
splits = split_partition_a(partitions["A"])

print(f"Loaded {len(trees)} trees")

for name, indices in partitions.items():
    print(f"Partition {name}: {len(indices)} trees")

for name, indices in splits.items():
    print(f"Partition A {name}: {len(indices)} trees")

output = Path("data/partition_indices.json")
output.parent.mkdir(parents=True, exist_ok=True)

saved_indices = {
    "partitions": partitions,
    "partition_a_splits": splits,
}
output.write_text(json.dumps(saved_indices, indent=2), encoding="utf-8")
print(f"Saved indices to {output.resolve()}")

def clean_tree_labels(tree):
    def clean(node):
        if node.label() == "-NONE-":
            return None

        children = []
        for child in node:
            if isinstance(child, Tree):
                cleaned_child = clean(child)
                if cleaned_child is not None:
                    children.append(cleaned_child)
            else:
                children.append(child)

        if not children:
            return None

        label = node.label()
        if not label.startswith("-"):
            label = label.split("-", 1)[0].split("=", 1)[0]

        return Tree(label, children)

    return clean(tree)

example = Tree.fromstring(
    "(S (NP-SBJ-1 (DT The) (NN dog)) (VP (VBZ runs)))"
)

print("Before:", example)
print("After: ", clean_tree_labels(example))

train_trees = [clean_tree_labels(trees[i]) for i in splits["train"]]
print(f"Training trees with cleaned labels: {len(train_trees)}")

trace_index = next(
    i for i in splits["train"]
    if any(node.label() == "-NONE-" for node in trees[i].subtrees())
)

original = trees[trace_index]
cleaned = clean_tree_labels(original)

print("Original words:", original.leaves())
print("Cleaned words: ", cleaned.leaves())
print("Trace nodes left:", sum(
    node.label() == "-NONE-" for node in cleaned.subtrees()
))
print("Training trees:", len(train_trees))

validation_trees = [
    clean_tree_labels(trees[i]) for i in splits["validation"]
]
test_trees = [
    clean_tree_labels(trees[i]) for i in splits["test"]
]

assert all(
    tree is not None
    for tree in train_trees + validation_trees + test_trees
)

print("Train:", len(train_trees))
print("Validation:", len(validation_trees))
print("Test:", len(test_trees))

